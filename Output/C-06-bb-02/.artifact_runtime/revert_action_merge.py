def main():
    total = 0
    for rel, pairs in JOBS:
        path = os.path.join(DESIGN, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            print("跳过（不存在）:", rel)
            continue
        text = io.open(path, encoding="utf-8").read()
        hits = 0
        for old, new in pairs:
            if old == new:
                continue
            if old not in text:
                print("  未命中:", os.path.basename(rel), "|", old[:34])
                continue
            text = text.replace(old, new)
            hits += 1
        if hits:
            io.open(path, "w", encoding="utf-8", newline="\n").write(text)
            total += hits
            print("%-34s %d 处" % (os.path.basename(rel), hits))
    print("\n合计替换:", total)


if __name__ == "__main__":
    main()
