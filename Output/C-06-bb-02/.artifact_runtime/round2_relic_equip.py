def read(path):
    return io.open(path, encoding="utf-8").read()


def write(path, text):
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)


def repoint_all():
    touched = 0
    for root, dirs, files in os.walk(COMBAT):
        dirs[:] = [d for d in dirs if d != "归档"]
        for name in files:
            if not name.endswith((".md", ".csv")):
                continue
            path = os.path.join(root, name)
            # 不修改历史版本文件
            if name.endswith(("_v1.md", "_v2.md")) and not name.startswith("06_战斗索引"):
                continue
            if name == "06_战斗索引_v2.md":
                continue
            text = read(path)
            original = text
            for old, new in REPOINT:
                text = text.replace(old, new)
            if text != original:
                write(path, text)
                touched += 1
                print("改指:", os.path.relpath(path, COMBAT))
    print("改指文件数:", touched)


