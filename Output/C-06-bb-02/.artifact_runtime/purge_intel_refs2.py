def main():
    total = 0
    miss = []
    for rel, old, new in RULES:
        path = os.path.join(DESIGN, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            miss.append((rel, "文件不存在"))
            continue
        text = io.open(path, encoding="utf-8").read()
        if old not in text:
            miss.append((rel, old[:34]))
            continue
        io.open(path, "w", encoding="utf-8", newline="\n").write(text.replace(old, new))
        total += 1
        print("%-40s OK  %s" % (rel.split("/")[-1], old[:34]))
    print("\n替换:", total)
    for rel, old in miss:
        print("未命中:", rel, "|", old)


if __name__ == "__main__":
    main()
