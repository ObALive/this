def read(p):
    return io.open(p, encoding="utf-8").read()


def write(p, t):
    io.open(p, "w", encoding="utf-8", newline="\n").write(t)


def sub(text, old, new, label, count=1):
    if old not in text:
        print("  未命中:", label)
        return text
    return text.replace(old, new, count)


