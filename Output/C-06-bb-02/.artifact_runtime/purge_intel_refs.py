def main():
    total = 0
    missing = []
    for rel, old, new in RULES:
        if not old:
            continue
        path = os.path.join(DESIGN, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            missing.append((rel, "文件不存在"))
            continue
        text = io.open(path, encoding="utf-8").read()
        count = text.count(old)
        if count == 0:
            missing.append((rel, old[:28]))
            continue
        io.open(path, "w", encoding="utf-8", newline="\n").write(text.replace(old, new))
        total += count
        print("%-58s %d 处  %s" % (rel.split("/")[-1], count, old[:30]))
    print("\n替换合计:", total)
    if missing:
        print("未命中:")
        for rel, old in missing:
            print("   ", rel, "|", old)


if __name__ == "__main__":
    main()
