def main():
    dump = load_dump()
    conn = sqlite3.connect(DB)
    conn.executescript(SCHEMA.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS")
                       .replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS")
                       .replace("CREATE VIEW", "CREATE VIEW IF NOT EXISTS"))
    conn.executescript(ARCHIVE_SCHEMA)
    archived = archive_gaps(conn, dump)
    open_gaps = rebuild_open_gaps(conn)
    conn.commit()

    report = {
        "db": os.path.relpath(DB, OUTPUT_DIR),
        "archived_rows": archived,
        "open_gaps": open_gaps,
        "open_candidates": conn.execute(
            "SELECT COUNT(*) FROM solution_options WHERE is_custom=0").fetchone()[0],
        "open_custom_rows": conn.execute(
            "SELECT COUNT(*) FROM solution_options WHERE is_custom=1").fetchone()[0],
        "pending_decisions": conn.execute(
            "SELECT COUNT(*) FROM decisions WHERE status='待裁定'").fetchone()[0],
        "archive_doc": os.path.basename(write_archive_doc(dump)),
        "new_doc": os.path.basename(write_new_doc()),
    }
    conn.close()
    print(json.dumps(report, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
