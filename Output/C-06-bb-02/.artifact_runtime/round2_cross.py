def main():
    for rel, old, new in JOBS:
        path = os.path.join(DESIGN, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            print("跳过:", rel)
            continue
        t = io.open(path, encoding="utf-8").read()
        if old not in t:
            print("未命中:", rel.split("/")[-1], "|", old[:30])
