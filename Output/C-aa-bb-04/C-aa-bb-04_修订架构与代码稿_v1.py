ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
changes = {}
def read(p):
    if p not in changes:
        b = (ROOT / p).read_bytes()
        changes[p] = [b, b.decode('utf-8-sig').replace('\r\n', '\n')]
    return changes[p][1]
def put(p, text):
    read(p)
    changes[p][1] = text
def rep(p, old, new, n=None):
    t = read(p)
    found = t.count(old)
    assert found and (n is None or found == n), (p, old, found, n)
    put(p, t.replace(old, new))

