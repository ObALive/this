modified=[]
for p,(before,t) in changes.items():
    if t==before.decode('utf-8-sig').replace('\r\n','\n'):
        continue
    t=re.sub(r'\| 更新日期 \| [^|\n]+ \|','| 更新日期 | 2026-10-23 |',t)
    subprocess.run(['git','cat-file','-e','HEAD:'+p],cwd=ROOT,check=True)
    assert (ROOT/p).read_bytes()==before
    newline='\r\n' if b'\r\n' in before else '\n'
    data=t.replace('\n',newline).encode('utf-8')
    if before.startswith(b'\xef\xbb\xbf'): data=b'\xef\xbb\xbf'+data
    modified.append((p,before,data))
target=OUT/'C-aa-bb-04_补充职责变更清单_v1.json'
