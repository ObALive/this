def main() -> None:
    for row in ROWS:
        assert (ROOT / row["notes"].split("来源：", 1)[1].split(" §", 1)[0].split(" 行 ", 1)[0]).is_file()
    for source_name in ("物品表", "行为表"):
        with (ROOT / SOURCES[source_name]).open(encoding="utf-8-sig", newline="") as stream:
            source_rows = list(csv.DictReader(stream))
        id_column = "操作ID" if source_name == "物品表" else "行为ID"
        statuses = {record[id_column]: record["Demo状态"] for record in source_rows}
        for row in ROWS:
            marker = f"来源：{SOURCES[source_name]} 行 "
            if row["notes"].startswith(marker):
                source_id = row["notes"].removeprefix(marker).split("；", 1)[0]
                if statuses.get(source_id) != "已确认":
                    raise SystemExit(f"来源行并非已确认：{source_id}")
    with sqlite3.connect(DB) as con:
        con.execute("PRAGMA foreign_keys=ON")
        if con.execute("SELECT COUNT(*) FROM mappings").fetchone()[0] != 0:
            raise SystemExit("工作库已经有明细；为避免重复导入，本脚本拒绝再次执行")
        known = {r[0] for r in con.execute("SELECT topic_id FROM topics")}
        if {r["topic_id"] for r in ROWS} - known:
            raise SystemExit("存在工作库中没有的反馈主题")
        # 现行信息传递设计稿已明确：对话不提供事件分支选择。
        changed = con.execute("""
            UPDATE topics
               SET player_behavior = ?, feedback_topic = ?, source_ref = ?,
                   updated_at = CURRENT_TIMESTAMP
             WHERE topic_id = 'FB-13'
               AND player_behavior = '推进对话或选择对话项'
               AND feedback_topic = '台词与事件分支反馈'
        """, (
            "在对话框中触发或推进台词",
            "台词呈现与段落推进反馈",
            "信息传递系统 §3.2、§3.5",
        ))
        if changed.rowcount != 1:
            raise SystemExit("FB-13 原主题文本与预期不符，停止导入以避免误改")
        con.executemany("""
            INSERT INTO mappings(topic_id, player_action, program_feedback,
                                 context, condition_text, notes, sort_order)
            VALUES (:topic_id, :player_action, :program_feedback,
                    :context, :condition_text, :notes, :sort_order)
        """, ROWS)
    with OUT.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(ROWS[0]))
        writer.writeheader()
        writer.writerows(ROWS)
    print(f"写入 {len(ROWS)} 条，覆盖 {len({r['topic_id'] for r in ROWS})} 个主题；审阅清单：{OUT}")


if __name__ == "__main__":
    main()
