ROWS: list[dict[str, str | int]] = []


def add(topic: str, action: str, feedback: str, source: str, section: str,
        context: str = "", condition: str = "", note: str = "") -> None:
    if source not in SOURCES or not (ROOT / SOURCES[source]).is_file():
        raise ValueError(f"来源文件缺失：{source}")
    citation = f"来源：{SOURCES[source]} {'行 '+section if source.endswith('表') else '§'+section}"
    if note:
        citation += f"；{note}"
    ROWS.append({
        "topic_id": topic, "player_action": action, "program_feedback": feedback,
        "context": context, "condition_text": condition, "notes": citation,
        "sort_order": 1 + sum(row["topic_id"] == topic for row in ROWS),
    })


