def main():
    changed = 0
    for rel, old, new in EDITS:
        path = to_abs('Dsh/Design/' + rel)
        if not os.path.isfile(path):
            print('MISS 文件缺失 %s' % rel)
            continue
        text = io.open(path, encoding='utf-8').read()
        n = text.count(old)
        if n != 1:
            print('MISS %s 命中 %d' % (rel, n))
            continue
        text = text.replace(old, new)
        ver_old, date_old, row_old, row_new = MERGE_ROW_ANCHORS[rel]
        if ver_old:
            text = text.replace(ver_old, ver_old.replace('v2.6', 'v2.7'))
        text = text.replace(date_old, date_old, 1)
        if text.count(row_old) == 1:
            text = text.replace(row_old, row_old + '\n' + row_new)
        else:
            print('  提示 %s 变更记录锚点未命中，需人工补录' % rel)
        if APPLY:
            io.open(path, 'w', encoding='utf-8', newline='\n').write(text)
        changed += 1
        print('OK   %s' % rel)
    print('改写 %d 份；模式：%s' % (changed, '写入' if APPLY else '预览'))


if __name__ == '__main__':
    main()
