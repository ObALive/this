def build():
    gaps, options = [], {}
    for gap_id, title, level, src, impact, close, owner, items in GAPS:
        gaps.append(GapRecord(gap_id=gap_id, title=title, level=level,
                              source_ref=src, impact_scope=impact,
                              close_condition=close, owner=owner,
                              priority_round='后续澄清，C-07-bb-02'))
        options[gap_id] = [OptionRecord('ABC'[i], t, d, tr, i == 0)
                           for i, (t, d, tr) in enumerate(items)]
    return gaps, options


def main():
    gaps, options = build()
    db_path = to_abs(DB_PATH)
    if not APPLY:
        print(json.dumps({
            '模式': '预览',
            '库': to_rel(db_path),
            '将追加缺口': len(gaps),
            '将追加候选': sum(len(v) for v in options.values()),
            '编号区间': '%s - %s' % (gaps[0].gap_id, gaps[-1].gap_id),
        }, ensure_ascii=False, indent=1))
        return
    summary = append_decision_db(db_path, gaps, options, analysis_doc=ANALYSIS_DOC)
    summary['path'] = to_rel(db_path)
    print(json.dumps(summary, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
