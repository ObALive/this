def read(path):
    return io.open(path, encoding='utf-8').read()


def write(path, text):
    io.open(path, 'w', encoding='utf-8', newline='\n').write(text)


def main():
    reports = []
    for rel_file in PATH_TARGETS:
        abs_path = to_abs('Dsh/Design/' + rel_file)
        if not os.path.isfile(abs_path):
            reports.append(('FILE-MISSING', rel_file, 0))
            continue
        text = read(abs_path)
        total = 0
        for old, new in PATH_REPLACEMENTS:
            n = text.count(old)
            if n:
                text = text.replace(old, new)
                total += n
        if total and APPLY:
            write(abs_path, text)
        reports.append(('path-refs', rel_file, total))

    for rel_path, old, new in EDITS:
        abs_path = to_abs('Dsh/Design/' + rel_path)
        if not os.path.isfile(abs_path):
            reports.append(('FILE-MISSING', rel_path, 0))
            continue
        text = read(abs_path)
        n = text.count(old)
        if n == 0:
            reports.append(('MISS', rel_path + ' | ' + old[:40], 0))
            continue
        text = text.replace(old, new)
        if APPLY:
            write(abs_path, text)
        reports.append(('OK', rel_path + ' | ' + old[:40], n))

    for state, note, n in reports:
        print('%-8s %-72s %s' % (state, note, n))
    print('')
    print('模式：%s' % ('写入' if APPLY else '预览'))


if __name__ == '__main__':
    main()
