def main():
    changed = 0
    for rel, old, new in EDITS:
        path = to_abs('Dsh/Design/' + rel)
        if not os.path.isfile(path):
            print('MISS 文件缺失 %s' % rel)
            continue
        text = io.open(path, encoding='utf-8').read()
        n = text.count(old)
        if n != 1:
            print('MISS %s 命中 %d :: %s' % (rel, n, old[:50].replace('\n', ' / ')))
            continue
        text = text.replace(old, new)
        changed += 1
        print('OK   %s :: %s' % (rel, old[:46].replace('\n', ' / ')))

    for rel, (vo, vn, do, dn, ro, rn, bo) in VERSIONS.items():
        path = to_abs('Dsh/Design/' + rel)
        text = io.open(path, encoding='utf-8').read()
        for a, b in ((vo, vn), (do, dn), (ro, rn)):
            if a != b and text.count(a) == 1:
                text = text.replace(a, b)
                changed += 1
            elif a != b:
                print('  提示 %s 版本/依据锚点命中 %d 次：%s' % (rel, text.count(a), a[:40]))
        if bo:
            import re
            text = re.sub(r'\| 设计依据 \|[^\n]*\|', bo, text, count=1)
            changed += 1
        if APPLY:
            io.open(path, 'w', encoding='utf-8', newline='\n').write(text)

    print('\n正文替换 %d 处；模式：%s' % (changed, '写入' if APPLY else '预览'))


if __name__ == '__main__':
    main()
