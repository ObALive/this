def build_options():
    mapping = {}
    for gap_id, items in OPTION_SOURCES:
        opts = []
        for label, title, detail, tradeoff in items:
            opts.append({
                'label': label,
                'title': title,
                'detail': detail,
                'tradeoff': tradeoff,
                'recommended': False,
            })
        mapping[gap_id] = opts
    return mapping


