def main():
    analysis_abs = to_abs(ANALYSIS)
    if not os.path.isfile(analysis_abs):
        raise SystemExit('分析文档不存在：%s' % ANALYSIS)
    gaps, qgap = load_analysis(analysis_abs)
    options = build_options()
    gaps_by_id = {g['gap_id']: g for g in gaps}
    order = ['MET-GAP-%03d' % i for i in range(1, len(gaps) + 1)]
    assert set(order) == set(gaps_by_id), 'GAP 编号不连续'

    problems = []
    records = []
    for gap_id in order:
        gap = gaps_by_id[gap_id]
        opts = options.get(gap_id)
        if opts is None:
            problems.append('%s 在 OPTION_SOURCES 中没有条目' % gap_id)
            opts = []
        rec = RECOMMENDED.get(gap_id)
        for opt in opts:
            opt['recommended'] = (opt['label'] == rec)
        if rec and not any(o['recommended'] for o in opts):
            problems.append('%s 的推荐候选 %s 不在候选清单中' % (gap_id, rec))
        records.append({
            'gap_id': gap_id,
            'title': gap['title'],
            'level': gap['level'],
            'source_ref': gap['source_ref'],
            'impact_scope': gap['impact_scope'],
            'close_condition': gap['close_condition'],
            'owner': gap['owner'],
            'priority_round': gap['priority_round'],
            # 没有候选的缺口属分析阶段认定的明显设计空缺，登记为开放填写：
            # 不设候选项，由自定义输入框直接承载需要设计的内容。
            'status': '开放填写' if not opts else '待裁定',
            'options': [
                {'label': o['label'], 'title': o['title'], 'detail': o['detail'],
                 'tradeoff': o['tradeoff'], 'recommended': o['recommended']}
                for o in opts
            ],
        })

    data = {
        'meta': {
            'title': 'C-07-bb-01 线索树与元进度缺口决策库',
            'chapter': 'C-07-bb-01',
            'domain': '07-线索树与元进度',
            'analysis_doc': ANALYSIS,
            'created_at': CREATED_AT,
        },
        'db_path': DB_PATH,
        'gaps': records,
    }
    out_abs = to_abs(OUT_PATH)
    io.open(out_abs, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(data, ensure_ascii=False, indent=1))

    with_options = sum(1 for r in records if r['options'])
    no_options = [r['gap_id'] for r in records if not r['options']]
    print(json.dumps({
        'data_file': to_rel(out_abs),
        'gaps': len(records),
        'gaps_with_options': with_options,
        'gaps_without_options': no_options,
        'options_total': sum(len(r['options']) for r in records),
        'problems': problems,
    }, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
