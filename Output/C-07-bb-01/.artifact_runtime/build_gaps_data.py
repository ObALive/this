def load_analysis(path):
    text = io.open(path, encoding='utf-8').read()
    lines = text.split('\n')

    # 问题号 -> 所属轮次（与分析文档第 5 节的分轮一致）
    rounds = {
        'MET-Q-001': '第一轮 本域骨架', 'MET-Q-002': '第一轮 本域骨架',
        'MET-Q-003': '第一轮 本域骨架', 'MET-Q-004': '第一轮 本域骨架',
        'MET-Q-005': '第一轮 本域骨架', 'MET-Q-006': '第一轮 本域骨架',
        'MET-Q-007': '第一轮 本域骨架', 'MET-Q-008': '第一轮 本域骨架',
        'MET-Q-009': '第二轮 跨局契约与写入', 'MET-Q-010': '第二轮 跨局契约与写入',
        'MET-Q-011': '第二轮 跨局契约与写入', 'MET-Q-012': '第二轮 跨局契约与写入',
        'MET-Q-013': '第三轮 解锁判定与呈现', 'MET-Q-014': '第三轮 解锁判定与呈现',
        'MET-Q-015': '第四轮 扩展与命名',
    }
    qgap = {}
    for line in lines:
        if line.startswith('| MET-Q-'):
            left = line.split('|')[1]
            ids = re.findall(r'MET-Q-\d{3}', left)
            if ids:
                qgap[ids[0]] = re.findall(r'MET-GAP-\d{3}', left)

    gaps = []
    for line in lines:
        if not re.match(r'^\| MET-GAP-\d{3} \|', line):
            continue
        cells = [c.strip() for c in line.split('|')]
        # cells[0] 为空串，cells[1] 为 ID
        gap_id, title_cell, source, impact, level, close, owner, status = cells[1:9]
        # 还原标题与影响范围：GAP 表把两者写在同一列，以“，影响…”为分界
        title = title_cell
        if not impact:
            m = re.match(r'^(.+?)，影响', title_cell)
            if m:
                title = m.group(1)
                impact = title_cell[m.end() - 1:].lstrip('，')
        q = re.search(r'MET-Q-\d{3}', status)
        priority = ''
        if q:
            priority = '%s，%s' % (rounds.get(q.group(0), ''), q.group(0))
        gaps.append({
            'gap_id': gap_id,
            'title': title,
            'level': level,
            'source_ref': source,
            'impact_scope': impact,
            'close_condition': close,
            'owner': owner,
            'status_raw': status,
            'priority_round': priority,
        })
    if not gaps:
        raise SystemExit('未从分析文档中解析到 GAP 表：%s' % path)
    return gaps, qgap


