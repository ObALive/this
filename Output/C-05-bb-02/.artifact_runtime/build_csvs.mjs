function makeCsv(headers, rows) {
  const esc = (value) => {
    const s = String(value ?? "");
    return /[",\r\n]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
  };
  return [headers, ...rows].map((row) => row.map(esc).join(",")).join("\r\n") + "\r\n";
}

async function buildAndVerify(name, headers, rows, outputPath) {
  const workbook = Workbook.create();
  const sheet = workbook.worksheets.add(name);
  sheet.getRangeByIndexes(0, 0, rows.length + 1, headers.length).values = [headers, ...rows];
  sheet.freezePanes.freezeRows(1);
  const headerRange = sheet.getRangeByIndexes(0, 0, 1, headers.length);
  headerRange.format.fill = "#1F4E78";
  headerRange.format.font = { bold: true, color: "#FFFFFF" };
  const used = sheet.getUsedRange();
  used.format.wrapText = true;
  used.format.verticalAlignment = "center";
  const inspect = await workbook.inspect({
    kind: "sheet,region",
    sheetId: name,
    range: `A1:N${rows.length + 1}`,
    maxChars: 6000,
    tableMaxRows: 6,
    tableMaxCols: 14,
    tableMaxCellChars: 100
  });
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, "\ufeff" + makeCsv(headers, rows), "utf8");
  return { name, rows: rows.length, columns: headers.length, inspect: inspect.ndjson };
}

